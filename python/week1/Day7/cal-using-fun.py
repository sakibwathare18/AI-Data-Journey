def add(a,b):
    return a + b
def substract(a,b):
    return a - b
def multiply(a,b):
    return a * b
def divide(a,b):
    return a / b

x = int(input("Enter First Number :"))
y = int(input("Enter Second Number :"))

print("Addition :",add(x,y))
print("Substraction :",substract(x,y))
print("Multiplication :",multiply(x,y))
print("Division :",divide(x,y))